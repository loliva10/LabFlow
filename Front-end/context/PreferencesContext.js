const PreferencesContext = createContext(null);

export function PreferencesProvider({ children }) {
  const [theme, setTheme] = useState('claro');
  const [language, setLanguage] = useState('pt');
  const [notifEmail, setNotifEmail] = useState(true);
  const [notifSistema, setNotifSistema] = useState(true);
  const [loaded, setLoaded] = useState(false);

  useEffect(() => {
    let ativo = true;
    AsyncStorage.getItem(STORAGE_KEY)
      .then((raw) => {
        if (!raw || !ativo) return;
        const p = JSON.parse(raw);
        if (themes[p.theme]) setTheme(p.theme);
        if (translations[p.language]) setLanguage(p.language);
        if (typeof p.notifEmail === 'boolean') setNotifEmail(p.notifEmail);
        if (typeof p.notifSistema === 'boolean') setNotifSistema(p.notifSistema);
      })
      .catch(() => {})
      .finally(() => {
        if (ativo) setLoaded(true);
      });
    return () => {
      ativo = false;
    };
  }, []);

  useEffect(() => {
    if (!loaded) return;
    AsyncStorage.setItem(
      STORAGE_KEY,
      JSON.stringify({ theme, language, notifEmail, notifSistema })
    ).catch(() => {});
  }, [theme, language, notifEmail, notifSistema, loaded]);

  const alterarTema = useCallback((novo) => {
    if (themes[novo]) setTheme(novo);
  }, []);

  const alterarIdioma = useCallback((novo) => {
    if (translations[novo]) setLanguage(novo);
  }, []);

  const t = useCallback(
    (key) => translations[language]?.[key] ?? translations.pt[key] ?? key,
    [language]
  );

  const value = useMemo(
    () => ({
      theme,
      isDark: theme === 'escuro',
      setTheme: alterarTema,
      language,
      setLanguage: alterarIdioma,
      notifEmail,
      setNotifEmail,
      notifSistema,
      setNotifSistema,
      colors: themes[theme],
      t,
    }),
    [theme, language, notifEmail, notifSistema, t, alterarTema, alterarIdioma]
  );

  if (!loaded) return null;

  return (
    <PreferencesContext.Provider value={value}>
      <View style={{ flex: 1, backgroundColor: themes[theme].bg }}>{children}</View>
    </PreferencesContext.Provider>
  );
}

export function usePreferences() {
  const ctx = useContext(PreferencesContext);
  if (!ctx) {
    throw new Error('usePreferences deve ser usado dentro de <PreferencesProvider>');
  }
  return ctx;
}

export function useThemedStyles(createStyles) {
  const { colors } = usePreferences();
  return useMemo(() => createStyles(colors), [colors]);
}